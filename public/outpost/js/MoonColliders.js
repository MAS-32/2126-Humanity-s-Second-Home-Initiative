// ============================================================
// MoonColliders — 简化碰撞世界（Simplified Collider System）
// 视觉模型负责"看"，本模块负责"挡"。
//   circles    圆柱近似 {x,z,r,y0,y1}
//   obbs       旋转盒   {x,z,hx,hz,c,s,y0,y1}
//   platforms  可行走平台 {x,z,rIn,rOut,y}（rIn 内平顶，rIn→rOut 坡道）
// y0/y1 为碰撞体的垂足高度区间（省略 = 全高）。
// 高架走廊等底部 >1.9m 的结构，地面玩家可从下方穿行，
// 走上平台后仍会被阻挡 —— 既无空气墙，也不穿模。
// 装饰灯杆 / 细设备 / 低矮台阶不设碰撞。
// ============================================================

const PLAYER_R = 0.55;      // 玩家半径
const HEAD = 1.8;           // 玩家头顶（相对足底）
const STEP_MAX = 2.4;       // 低重力下允许直接迈上的高度

export function buildCollisionWorld(heightAt) {
  const circles = [];
  const obbs = [];
  const platforms = [];

  const C = (x, z, r, y0, y1) => circles.push({ x, z, r, y0, y1 });
  const B = (x, z, hx, hz, ry = 0, y0, y1) => obbs.push({ x, z, hx, hz, c: Math.cos(ry), s: Math.sin(ry), y0, y1 });
  const P = (x, z, rIn, rOut, y) => platforms.push({ x, z, rIn, rOut, y });
  // 线段走廊 → OBB（本地 x 轴沿 (x1,z1)→(x2,z2)）
  const seg = (x1, z1, x2, z2, hw, y0, y1) => {
    const dx = x2 - x1, dz = z2 - z1, len = Math.hypot(dx, dz);
    B((x1 + x2) / 2, (z1 + z2) / 2, len / 2, hw, Math.atan2(-dz, dx), y0, y1);
  };

  /* ---------------- CENTRAL HUB（原点） ---------------- */
  P(0, 0, 31, 33, 1.6); P(0, 0, 26, 28.5, 3.3); P(0, 0, 19, 22, 4.8);
  C(0, 0, 15.8);                                   // 主大厅鼓形
  // 放射连廊：管底 1.95m → 地面玩家（头 1.8）从下方穿行，上平台后阻挡
  for (const a of [-0.298, -2.915, -1.75, 0.95, 2.2]) {
    seg(Math.cos(a) * 14, Math.sin(a) * 14, Math.cos(a) * 33, Math.sin(a) * 33, 1.6, 1.85, 4.2);
  }
  const hubMods = [
    { a: 0.55, d: 40, t: 'h7' }, { a: 1.95, d: 38, t: 't3.2' },
    { a: 2.75, d: 42, t: 'h9' }, { a: 3.6, d: 39, t: 't2.8' },
    { a: 4.6, d: 41, t: 'h6' },  { a: 5.5, d: 37, t: 't3.4' },
  ];
  for (const m of hubMods) {
    const x = Math.cos(m.a) * m.d, z = Math.sin(m.a) * m.d;
    seg(Math.cos(m.a) * 27, Math.sin(m.a) * 27, Math.cos(m.a) * (m.d - 3), Math.sin(m.a) * (m.d - 3), 1.4, 1.65, 3.6);
    if (m.t === 'h7') B(x, z, 3.9, 2.6, -m.a + Math.PI / 2);
    else if (m.t === 'h9') B(x, z, 4.9, 2.9, -m.a + Math.PI / 2);
    else if (m.t === 'h6') B(x, z, 3.4, 2.5, -m.a + Math.PI / 2);
    else C(x, z, parseFloat(m.t.slice(1)));
  }
  C(4.2, 26, 0.5); C(-4.2, 26, 0.5);               // 广场门柱
  C(0, 11, 1.3);                                    // 欢迎终端
  C(18, 20, 1.3);                                   // 小天线（通讯杆太细不挡）
  C(8, 35, 0.7); C(-8, 35, 0.7);                    // 信息柱
  C(-9, 34, 1.4);                                   // 服务亭

  /* ---------------- ECO DOME（130,-40） ---------------- */
  // 平台在入口(+z)不外溢：气闸(21.4)在 rOut 之外，玩家平地过闸再上平台
  P(130, -40, 19, 21, 2.2);
  // 玻璃穹顶：环形墙碰撞（非实心圆柱），+z 朝向 hub 留入口缺口，玩家可真正走进穹顶
  for (let a = 0; a < Math.PI * 2; a += 0.10) {
    if (Math.abs(a - Math.PI / 2) < 0.11) continue;   // 入口缺口（+z）
    C(130 + Math.cos(a) * 21.4, -40 + Math.sin(a) * 21.4, 1.0);
  }
  C(130, -40, 3.0);                                   // 中央生命塔（穹顶内部）
  B(134, -8, 11.5, 4.9, 0.35);                        // 长条温室
  // 入口气闸：两侧墙，中间 1.5m 门洞通行（不再是实心盒封死）
  B(128.5, -18.6, 0.75, 1.6, 0);
  B(131.5, -18.6, 0.75, 1.6, 0);
  C(135.5, -15, 1.1);                                 // WATER 监测台
  C(142, -2, 0.8);                                    // LIGHT 终端
  C(124, -17, 0.8);                                   // OXYGEN 终端

  /* ---------------- RESEARCH VILLAGE（-130,-30） ---------------- */
  P(-130, -30, 26, 28, 1.0);
  B(-136, -30, 4.9, 3.0, 0.4);
  B(-123, -23, 3.9, 2.7, -0.5);
  B(-119, -36, 5.9, 3.2, 1.25);
  C(-143, -23, 3.7); C(-129, -43, 3.0); C(-113, -21, 2.6);
  B(-146, -37, 3.4, 2.4, 0.9);
  C(-132, -14, 6.2);
  // 村内加压连廊：管底 1.4m，位于可走基盘（1.0m）上方 → 盘上玩家被挡
  seg(-136, -30, -123, -23, 1.4, 1.3, 3.2); seg(-123, -23, -119, -36, 1.4, 1.3, 3.2);
  seg(-136, -30, -143, -23, 1.4, 1.3, 3.2); seg(-136, -30, -146, -37, 1.4, 1.3, 3.2);
  seg(-129, -43, -119, -36, 1.4, 1.3, 3.2); seg(-136, -30, -132, -14, 1.4, 1.3, 3.2);
  seg(-136, -30, -154, -28, 1.4, 1.3, 3.2);
  seg(-119, -36, -109, -25, 1.4, 1.3, 3.2);
  seg(-146, -37, -150, -45, 1.4, 1.3, 3.2);
  seg(-123, -23, -116, -13, 1.4, 1.3, 3.2);
  C(-151, -17, 2.6); C(-111, -40, 1.6);             // 大小天线
  C(-115, -45, 0.5);                                // 通讯塔
  C(-122, -43, 1.7);                                // 月球车
  B(-154, -28, 3.9, 2.7, 0.3);                      // 医疗舱
  C(-116, -13, 3.4);                                // 生命维持塔
  C(-112, -15, 1.6); C(-112, -11, 1.6);
  C(-150, -45, 4.9);                                // 公共穹顶
  B(-109, -25, 4.4, 2.8, 1.0);
  C(-141, -50, 1.7);                                // 车泊位月球车
  C(-125, -50, 1.4); C(-123, -51, 1.4); C(-124, -48.5, 1.4);
  C(-148, -14, 0.9);                                // EARTH LINK 终端

  /* ---------------- ROCKET PORT（0,-165） ---------------- */
  P(0, -165, 24, 26, 2.0);
  C(0, -165, 3.6);                                  // 主船体
  C(-4.4, -165, 1.7); C(4.4, -165, 1.7);            // 双助推
  C(3.47, -162.63, 0.9); C(-2.47, -161.61, 0.9);
  C(-2.74, -168.23, 0.9); C(2.66, -168.32, 0.9);    // 支撑臂
  C(-10, -168, 4.8); C(10, -168, 4.4);              // 双子塔架
  C(18, -157, 3.3); C(25, -163, 3.3); C(18, -169, 3.3);  // 燃料罐
  // 燃料管线：沿垫面 0.28m 高 → 垫外地面不挡，垫上阻挡
  seg(18, -157, 12, -161, 0.9, 1.7, 2.6); seg(12, -161, 4, -165, 0.9, 1.7, 2.6);
  seg(18, -163, 10, -167, 0.8, 1.7, 2.6); seg(10, -167, 3.5, -166, 0.8, 1.7, 2.6);
  B(-18, -155, 4.1, 2.6, 0);                        // 发射控制楼
  B(16, -179, 3.1, 2.3, 0);                         // 服务楼
  C(-16, -145, 1.6); C(-13, -143, 1.6); C(-19, -142, 1.6); C(20, -147, 1.6);
  B(-4, -168, 1.4, 0.7, 0);                         // 发射控制终端
  C(12, -145, 2.0); C(16, -143, 2.0); C(20, -141, 2.0); C(24, -139, 2.0);
  B(-26, -173, 4.7, 3.7, 0);                        // 维修棚
  C(-24, -161, 2.8);                                // 设备塔
  P(28, -149, 5.4, 6.2, 0.5);
  C(28, -149, 3.0);                                 // 停放 VTOL
  C(20, -171, 1.7);                                 // 运输车
  C(14, -141, 0.8);                                 // VERIFY CARGO 终端
  C(15, -154, 0.8);                                 // CHECK ENERGY 终端

  /* ---------------- INFRASTRUCTURE ---------------- */
  P(34, -96, 13, 14, 1.2);
  B(35.5, -96, 3.2, 2.3, 0.5);                      // VTOL
  B(33, -79, 3.9, 2.6, 0.2);                        // 后勤舱
  C(96, -12, 3.9); C(100.5, -11, 1.5);              // 通讯塔 A + 天线
  C(-96, -86, 3.5); C(-100, -84.5, 1.3);            // 通讯塔 B + 天线
  C(66, -84, 3.0); B(71, -78, 3.4, 2.4, 1.1); B(-58, -96, 4.4, 2.6, 0.5);
  C(-64, -104, 2.6); B(-40, 72, 3.9, 2.5, 2.2); C(44, 78, 2.8);
  B(148, -96, 3.4, 2.4, -0.6); C(-148, -70, 3.2); C(-120, 24, 4.0); B(128, 6, 3.9, 2.5, 1.9);
  // 太阳能阵列 A/B：面板离地 1.9m、支柱纤细，玩家可从板下穿行参观。
  // 不再使用整块大 Box（那是 47×23 空气墙，把板间空隙与周边全封死）。
  C(14, -72, 1.7);                                  // 路边月球车
  B(92, -66, 3.4, 2.4, 0.8); C(-100, 30, 3.0);
  B(60, 20, 3.4, 2.4, -0.9); C(-60, -130, 3.2);

  /* ---------------- 城市功能设施（Phase 2 新增） ---------------- */
  B(72, 14, 3.5, 2.5, 0.3);                         // 能源分配站 A（太阳能支线东侧）
  B(-58, 12, 3.5, 2.5, -0.2);                       // 能源分配站 B
  C(61, -46, 2.2); C(67, -46, 2.2); B(64, -42, 3, 2, 0);   // 水处理设施
  C(-61, -40, 2.0); C(-67, -40, 2.0); B(-64, -36, 3, 2, 0); // 氧气循环厂
  B(150, -110, 5, 3.5, 0.4); C(158, -106, 2.4);     // 月壤资源处理场

  /* ---------------- 轨道车站（Phase 2 新增） ---------------- */
  // 站台：圆形可走平台（坡道上下）+ 四柱
  const stations = [[19, 52], [105, -36], [-96, -18], [20, -128]];
  for (const [sx, sz] of stations) {
    P(sx, sz, 4.6, 7.5, 3.0);
    for (const [ox, oz] of [[-2.8, -2.2], [2.8, -2.2], [-2.8, 2.2], [2.8, 2.2]]) {
      C(sx + ox, sz + oz, 0.35);
    }
  }

  /* ---------------- 查询接口 ---------------- */

  function platformGround(x, z) {
    let g = -Infinity;
    for (const p of platforms) {
      const d = Math.hypot(x - p.x, z - p.z);
      if (d >= p.rOut) continue;
      const t = d <= p.rIn ? 1 : (p.rOut - d) / (p.rOut - p.rIn);
      const cand = p.y * t;
      if (cand > g) g = cand;
    }
    return g;
  }

  function ground(x, z) {
    return Math.max(heightAt(x, z), platformGround(x, z));
  }

  // 垂足区间相交检测：玩家 [footY, footY+HEAD] 与碰撞体 [y0,y1]
  function vOverlap(c, footY) {
    if (c.y0 === undefined) return true;
    return footY < c.y1 && footY + HEAD > c.y0;
  }

  function collides(x, z, footY) {
    for (const c of circles) {
      if (!vOverlap(c, footY)) continue;
      const dx = x - c.x, dz = z - c.z;
      if (dx * dx + dz * dz < (c.r + PLAYER_R) * (c.r + PLAYER_R)) return true;
    }
    for (const b of obbs) {
      if (!vOverlap(b, footY)) continue;
      const dx = x - b.x, dz = z - b.z;
      const lx = b.c * dx - b.s * dz;
      const lz = b.s * dx + b.c * dz;
      if (Math.abs(lx) < b.hx + PLAYER_R && Math.abs(lz) < b.hz + PLAYER_R) return true;
    }
    const pg = platformGround(x, z);
    if (pg > -Infinity && pg - footY > STEP_MAX) return true;
    return false;
  }

  return { collides, ground, circles, obbs, platforms };
}
